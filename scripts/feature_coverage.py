"""Generate one honest status row for every FEATURE_MAP row; no inferred implementation claims."""

from pathlib import Path

source = Path("docs/FEATURE_MAP.md").read_text()
rows = []
section = ""
for line in source.splitlines():
    if line.startswith("## "):
        section = line[3:]
    if not line.startswith("|"):
        continue
    cells = [cell.strip() for cell in line.strip("|").split("|")]
    if len(cells) != 4 or cells[0] == "Frontend feature" or cells[0].startswith("---"):
        continue
    feature = cells[0].replace("|", "/")
    if section.startswith("Document uploads"):
        state, reason = "FLAGGED OFF", "M4b, scanner and advocate acceptance pending"
    else:
        state, reason = "BLOCKED", "M2 browser acceptance pending"
    rows.append(f"| {feature} | {state} | {reason} |")
status = Path("STATUS.md")
content = status.read_text()
start = content.index("## Feature coverage")
end = content.index("## Next action", start)
table = (
    "## Feature coverage\nGenerated by `python scripts/feature_coverage.py`; "
    "DONE requires an API, frontend path and tests.\n\n"
    "| Feature | Status | Reason |\n|---|---|---|\n" + "\n".join(rows) + "\n\n"
)
status.write_text(content[:start] + table + content[end:])
assert len(status.read_text().splitlines()) < 150, "STATUS.md exceeds handoff limit"
print(f"Generated {len(rows)} feature rows")
