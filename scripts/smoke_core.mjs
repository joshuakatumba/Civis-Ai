// FAKE identities and form values; real auth, database, storage and supplied catalog.
const { chromium } = await import(process.env.CIVIS_PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const browser = await chromium.launch({headless:true,executablePath:process.env.CIVIS_CHROMIUM || undefined,args:['--no-sandbox']});
const page = await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', error=>errors.push(error.message));
page.on('dialog', dialog=>dialog.accept());
const email=`FAKE-${crypto.randomUUID()}@example.invalid`;
const password='FAKE-a1-'+crypto.randomBytes(24).toString('hex');
const base=process.env.CIVIS_WEB_URL || 'http://localhost:53000';
try {
 await page.goto(base);
 await page.getByRole('heading',{name:'Legal help in plain language'}).waitFor();
 await page.getByRole('button',{name:'Forgot password?',exact:true}).click();
 await page.getByRole('heading',{name:'Reset your password'}).waitFor();
 assert.equal(new URL(page.url()).pathname,'/auth/reset-password');
 await page.reload();
 await page.getByRole('heading',{name:'Reset your password'}).waitFor();
 await page.getByRole('button',{name:'Back to log in',exact:true}).click();
 await page.getByRole('button',{name:'Sign up',exact:true}).click();
 await page.getByLabel('Full name').fill('FAKE Browser');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('button',{name:'Drafting',exact:true}).click();
 const search=page.locator('.ts input');
 await search.waitFor();
 await search.fill('Lease');
 await page.locator('.tc').first().waitFor();
 await search.fill('');
 const categoryIndex=await page.locator('.chip em').evaluateAll(nodes=>nodes.findIndex(n=>Number(n.textContent)>9));
 assert.ok(categoryIndex>=0);
 const category=page.locator('.chip').nth(categoryIndex);
 await category.click();
 await page.locator('.more').waitFor();
 await page.locator('.more').click();
 await page.waitForFunction(()=>!document.querySelector('.more'));
 await category.click();
 await search.fill('Lease Agreement');
 await page.locator('.tc').filter({hasText:'Lease Agreement'}).first().click();
 await page.locator('.panel .fld input').first().waitFor();
 const save=page.waitForResponse(r=>r.url().endsWith('/draft')&&r.request().method()==='PATCH');
 await page.locator('.panel .fld input').first().fill('FAKE Core Browser');
 assert.equal((await save).status(),200);
 await page.getByRole('button',{name:'Preview',exact:true}).click();
 await page.locator('.sheet').waitFor();
 await page.getByRole('button',{name:'Fields',exact:true}).click();
 const generated=page.waitForResponse(r=>r.url().endsWith('/render')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Generate',exact:true}).click();
 assert.equal((await generated).status(),200);
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).waitFor();
 const download=page.waitForEvent('download');
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).click();
 assert.match((await download).suggestedFilename(),/\.docx$/);
 await page.reload();
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).waitFor();
 await page.locator('.me').click();
 await page.getByRole('menuitem',{name:'Dark mode',exact:true}).click();
 await page.locator('.cv.dark').waitFor();
 await page.reload();
 await page.locator('.cv.dark').waitFor();
 await page.getByRole('button',{name:'Close sidebar',exact:true}).click();
 await page.locator('.side.min').waitFor();
 await page.getByRole('button',{name:'Open sidebar',exact:true}).click();
 await page.evaluate(()=>{Object.defineProperty(navigator.mediaDevices,'getUserMedia',{configurable:true,value:async()=>{throw new DOMException('FAKE denied','NotAllowedError');}});});
 await page.getByRole('button',{name:'Voice input',exact:true}).click();
 await page.locator('.toast').waitFor();
 await page.locator('.me').click();
 await page.getByRole('menuitem',{name:'Logout',exact:true}).click();
 await page.getByRole('button',{name:'Log out',exact:true}).click();
 await page.getByLabel('Email',{exact:true}).waitFor();
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Log in',exact:true}).last().click();
 await page.locator('.side').waitFor();
 assert.equal(await page.evaluate(()=>['civis-session','civis-accounts'].some(k=>localStorage.getItem(k))),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: landing/recovery/signup/login/catalog/search/category/paging/form/preview/generate/download/reload/settings/theme/sidebar/mic-denial; no JavaScript errors');
} finally {await browser.close();}
