// External QA dependency only; never add Playwright to the app dependencies.
const { chromium } = await import(process.env.CIVIS_PLAYWRIGHT_MODULE || "playwright");
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const browser = await chromium.launch({headless:true, executablePath:process.env.CIVIS_CHROMIUM || undefined,args:['--no-sandbox']});
const page = await browser.newPage({acceptDownloads:true, viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('401'))errors.push(m.text());});
page.on('dialog', d=>d.accept());
try {
 await page.goto(process.env.CIVIS_WEB_URL || 'http://localhost:53000');
 await page.getByRole('button',{name:'Sign up',exact:true}).click();
 await page.getByLabel('Full name').fill('FAKE Browser');
 await page.getByLabel('Email',{exact:true}).fill(`FAKE-${crypto.randomUUID()}@example.invalid`);
 await page.getByLabel('Password',{exact:true}).fill('FAKE-a1-'+crypto.randomBytes(24).toString('hex'));
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('button',{name:'Drafting',exact:true}).click();
 await page.locator('.bar textarea').fill('FAKE test. Please prepare a Lease Agreement between FAKE Alpha and FAKE Beta.');
 const prefill=page.waitForResponse(r=>r.url().endsWith('/v1/drafting/prefill'),{timeout:100000});
 await page.getByRole('button',{name:'Send',exact:true}).click();
 const response=await prefill;
 assert.equal(response.status(),200, 'prefill status');
 const data=await response.json();
 assert.equal(data.slug,'lease-agreement');
 assert.equal(data.values.a,'FAKE Alpha');
 assert.equal(data.values.b,'FAKE Beta');
 assert.equal(data.values.amt,null);
 await page.locator('.panel .fld input').first().waitFor();
 assert.equal(await page.locator('.panel .fld input').first().inputValue(),'FAKE Alpha');
 const save=page.waitForResponse(r=>r.url().endsWith('/draft')&&r.request().method()==='PATCH');
 await page.locator('.panel .fld input').first().fill('FAKE Edited');
 assert.equal((await save).status(),200);
 await page.reload();
 await page.locator('.panel .fld input').first().waitFor();
 assert.equal(await page.locator('.panel .fld input').first().inputValue(),'FAKE Edited');
 const generated=page.waitForResponse(r=>r.url().endsWith('/render')&&r.request().method()==='POST');
 await page.locator('.panel').getByRole('button',{name:'Generate',exact:true}).click();
 assert.equal((await generated).status(),200);
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).waitFor();
 const downloaded=page.waitForEvent('download');
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).click();
 assert.match((await downloaded).suggestedFilename(),/\.docx$/);
 await page.locator('.panel').getByRole('button',{name:'Fields',exact:true}).click();
 const editSave=page.waitForResponse(r=>r.url().endsWith('/draft')&&r.request().method()==='PATCH');
 await page.locator('.panel .fld input').first().fill('FAKE New');
 assert.equal((await editSave).status(),200);
 assert.equal(await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).count(),0);
 await page.reload();
 await page.locator('.panel .fld input').first().waitFor();
 assert.equal(await page.locator('.panel .fld input').first().inputValue(),'FAKE New');
 const regenerated=page.waitForResponse(r=>r.url().endsWith('/render')&&r.request().method()==='POST');
 await page.locator('.panel').getByRole('button',{name:'Generate',exact:true}).click();
 assert.equal((await regenerated).status(),200);
 await page.locator('.panel').getByRole('button',{name:'Download',exact:true}).waitFor();
 const keys=await page.evaluate(()=>Object.keys(localStorage));
 assert.equal(keys.some(k=>/account|password|session|token/i.test(k)),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: live Groq prefill, literal facts/missing fields, encrypted draft reload, edit invalidation, generate/regenerate/download, no browser errors/auth storage');
} finally {await browser.close();}
